fun resolvePalette(pref: ThemePreference, systemDark: Boolean): AppColors =
    when (pref) {
        ThemePreference.SYSTEM -> if (systemDark) Palettes.Dark else Palettes.Light
        ThemePreference.DARK -> Palettes.Dark
        ThemePreference.LIGHT -> Palettes.Light
        ThemePreference.OCEAN -> Palettes.Ocean
        ThemePreference.VOLT -> Palettes.Volt
    }

